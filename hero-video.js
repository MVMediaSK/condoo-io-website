(() => {
  const trigger = document.getElementById('hero-video-trigger');
  const modal = document.getElementById('hero-video-modal');
  if (!trigger || !modal || typeof modal.showModal !== 'function') return;
  const video = modal.querySelector('video');
  const player = modal.querySelector('.film-player');
  const controls = modal.querySelector('.film-controls');
  const toggle = modal.querySelector('.film-toggle');
  const mute = modal.querySelector('.film-mute');
  const seek = modal.querySelector('.film-seek');
  const time = modal.querySelector('.film-time');
  const status = modal.querySelector('.film-status');
  const full = modal.querySelector('.film-fullscreen');
  let origin;
  const clock = value => { const s = Math.max(0, Math.floor(value || 0)); return `${Math.floor(s / 60)}:${String(s % 60).padStart(2, '0')}`; };
  const message = text => { status.textContent = text; status.hidden = !text; };
  const sync = () => {
    const duration = Number.isFinite(video.duration) ? video.duration : 114;
    seek.max = duration; seek.value = video.currentTime;
    seek.setAttribute('aria-valuetext', `${clock(video.currentTime)} von ${clock(duration)}`);
    time.textContent = `${clock(video.currentTime)} / ${clock(duration)}`;
    player.classList.toggle('film-playing', !video.paused);
    toggle.setAttribute('aria-label', video.paused ? 'Abspielen' : 'Pausieren');
    player.classList.toggle('film-muted', video.muted);
    mute.setAttribute('aria-label', video.muted ? 'Ton einschalten' : 'Ton ausschalten');
    mute.setAttribute('aria-pressed', String(video.muted));
  };
  const play = () => { message(''); video.play().then(() => { if (!modal.open) video.pause(); }).catch(() => { if (modal.open) message('Drücke auf Play, um das Video zu starten.'); }); };
  trigger.addEventListener('click', event => {
    event.preventDefault(); origin = document.activeElement;
    modal.showModal(); document.documentElement.classList.add('film-open');
    if (!video.getAttribute('src')) { video.src = video.dataset.src; video.load(); }
    play();
  });
  modal.querySelector('.film-close').addEventListener('click', () => modal.close());
  let outside = false;
  modal.addEventListener('pointerdown', event => { outside = event.target === modal; });
  modal.addEventListener('click', event => { if (outside && event.target === modal) modal.close(); outside = false; });
  modal.addEventListener('close', () => { video.pause(); document.documentElement.classList.remove('film-open'); message(''); origin?.focus({preventScroll:true}); });
  toggle.addEventListener('click', () => video.paused ? play() : video.pause());
  video.addEventListener('click', () => video.paused ? play() : video.pause());
  mute.addEventListener('click', () => { video.muted = !video.muted; });
  seek.addEventListener('input', () => { if (Number.isFinite(video.duration)) video.currentTime = Number(seek.value); sync(); });
  ['timeupdate','loadedmetadata','play','pause','ended','volumechange'].forEach(event => video.addEventListener(event,sync));
  video.addEventListener('waiting', () => message('Video wird geladen …'));
  video.addEventListener('playing', () => message(''));
  video.addEventListener('canplay', () => message(''));
  video.addEventListener('error', () => message('Das Video konnte nicht geladen werden. Bitte versuche es erneut.'));
  full.hidden = !player.requestFullscreen && !video.webkitEnterFullscreen;
  full.addEventListener('click', async () => { try { if (document.fullscreenElement) await document.exitFullscreen(); else if (player.requestFullscreen) await player.requestFullscreen(); else video.webkitEnterFullscreen(); } catch { message('Vollbild ist in diesem Browser nicht verfügbar.'); } });
  document.addEventListener('fullscreenchange', () => full.setAttribute('aria-label', document.fullscreenElement ? 'Vollbild verlassen' : 'Vollbild öffnen'));
  video.controls = false; controls.hidden = false; sync();
})();
